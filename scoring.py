"""
Combine the model and stylometry signals, then map the score to reader-facing
labels.
"""

import config


def _clamp(value: float) -> float:
    return min(max(value, 0.0), 1.0)


def combine_signals(model_score: float, style_score: float) -> float:
    """
    Combine two 0-1 signals into one AI-likelihood score.

    The model signal gets 55% weight and the style signal gets 45%. When the
    signals strongly disagree, the result is pulled halfway toward 0.5 so the
    service prefers uncertainty over a confident accusation.
    """
    model_score = _clamp(float(model_score))
    style_score = _clamp(float(style_score))

    combined = (
        config.WEIGHT_MODEL_SIGNAL * model_score
        + config.WEIGHT_STYLE_SIGNAL * style_score
    )

    if abs(model_score - style_score) >= 0.35:
        combined = (combined + 0.5) / 2.0

    return round(_clamp(combined), 4)


def score_to_label(score: float) -> tuple[str, str]:
    """Turn the score into a machine guess and plain-English reader label."""
    score = _clamp(float(score))

    if score >= config.AI_THRESHOLD:
        return (
            "ai",
            "Our signals strongly suggest this text may be AI-generated. "
            "This is not proof, and the writer can appeal this result.",
        )

    if score <= config.HUMAN_THRESHOLD:
        return (
            "human",
            "Our signals suggest this text was probably written by a person.",
        )

    return (
        "unsure",
        "We cannot confidently tell whether this text was written by a person "
        "or generated by AI. No accusation should be made from this result.",
    )


def label_ranges() -> list[tuple[str, str]]:
    """The score range covered by each reader-facing label."""
    return [
        ("high-confidence human", f"0.00 – {config.HUMAN_THRESHOLD:.2f}"),
        ("unsure", f"{config.HUMAN_THRESHOLD:.2f} – {config.AI_THRESHOLD:.2f}"),
        ("high-confidence AI", f"{config.AI_THRESHOLD:.2f} – 1.00"),
    ]
